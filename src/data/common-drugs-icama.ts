import type { Drug } from '@/types';

type OfficialDrugInput = Pick<
  Drug,
  'id' | 'productName' | 'registeredName' | 'registrationNo' | 'holder' | 'formulationType' |
  'activeIngredients' | 'target' | 'environments' | 'applicationMethods' | 'indoorAllowed' |
  'outdoorAllowed' | 'notes' | 'registrationValidUntil'
> & Partial<Pick<Drug, 'uses' | 'doseBasis' | 'synonyms' | 'labelDate' | 'status'>>;

function officialDrug(input: OfficialDrugInput): Drug {
  const officialLabelUrl = `https://www.icama.cn/BasicdataSystem/pesticideRegistration/tagview.do?pdno=${input.registrationNo}`;
  const status = input.status ?? 'VERIFIED_REGISTRATION';
  return {
    manufacturer: '官方标签未单列生产企业',
    category: '卫生杀虫剂',
    diluent: 'water',
    status,
    labelSource: '农业农村部 ICAMA 农药标签',
    source: {
      type: 'ICAMA_OFFICIAL_LABEL',
      url: officialLabelUrl,
      verifiedAt: '2026-08-11',
    },
    verification: {
      status,
      verificationMethod: 'OFFICIAL_AUTO',
      officialSources: ['ICAMA_OFFICIAL_LABEL'],
      officialRegistrationUrl: 'https://www.icama.cn/BasicdataSystem/pesticideRegistration/queryselect.do',
      officialLabelUrl,
      verifiedAt: '2026-08-11',
      lastOfficialCheckAt: '2026-08-11',
      nextCheckAt: '2026-09-11',
      confidence: 'HIGH',
      officialMatched: true,
      warnings: status === 'VERIFIED_CALCULABLE' ? [] : ['官方标签和登记有效期均已核对，但当前标签剂量仍缺少安全换算参数'],
    },
    dataVersion: '2026.3',
    tier: 'B',
    ...input,
  };
}

